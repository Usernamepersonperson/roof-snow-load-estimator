"""Compute every number quoted in the README in one place and write docs/results.{json,md}."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from roofsnow import alerts, analysis, data, model, sensor

PRIMARY_WINTER = "2017/18"
FUSION_SEED = 7


def fusion_simulation(fx: pd.DataFrame, station: str = "ENG", winter: str = "2020/21",
                      noise_rel: float = 0.05, seed: int = FUSION_SEED) -> dict:
    """SIMULATED roof sensor: truth = Sturm-regression load (the 'roof' is assumed to follow it), model =
    layered settlement load, sensor = truth + 5 % Gaussian noise. Shows the effect of inverse-variance
    fusion only; no real sensor was used."""
    start, end = data.WINTERS[winter]
    df = data.select(fx, station, start, end)
    site = analysis.site_for(station)
    truth = model.compute(df, site, "sturm").table["roof_kn_m2"]
    est = model.compute(df, site, "layered").table["roof_kn_m2"]
    rng = np.random.default_rng(seed)
    meas = truth * (1 + rng.normal(0, noise_rel, len(truth)))
    fused = pd.Series([sensor.fuse(m, s, sensor_sigma_rel=noise_rel)[0] if m > 0 else 0.0
                       for m, s in zip(est, meas, strict=True)], index=truth.index)
    ok = truth.notna() & (truth > 0.2)
    rm = lambda a: float(np.sqrt(((a[ok] - truth[ok]) ** 2).mean()))  # noqa: E731
    return {"station": station, "winter": winter, "days": int(ok.sum()), "noise_rel": noise_rel,
            "rmse_model_kn_m2": round(rm(est), 3), "rmse_sensor_kn_m2": round(rm(meas), 3),
            "rmse_fused_kn_m2": round(rm(fused), 3)}


def build(fx: pd.DataFrame) -> dict:
    runs = analysis.run_all(fx)
    summ = analysis.summary_table(runs)
    cons = analysis.summary_table(analysis.run_all(fx, model_name="sturm"))
    sens = pd.concat([analysis.sensitivity(fx, st, PRIMARY_WINTER) for st in data.STATIONS])
    cross = analysis.crosscheck(fx)
    # alert behaviour: level changes over all 15 station-winters, with and without hysteresis
    n_with = sum(len(alerts.run_alerts(r.result.table["utilisation"], hysteresis=0.05).events) for r in runs)
    n_without = sum(len(alerts.run_alerts(r.result.table["utilisation"], hysteresis=0.0).events)
                    for r in runs)
    p = summ[summ.winter == PRIMARY_WINTER]
    return {
        "primary_winter": PRIMARY_WINTER,
        "winters": {k: list(v) for k, v in data.WINTERS.items()},
        "stations": {k: {"name": v[0], "altitude_m": v[1]} for k, v in data.STATIONS.items()},
        "summary": summ.to_dict("records"),
        "summary_conservative_sturm": cons.to_dict("records"),
        "sensitivity_primary": sens.to_dict("records"),
        "crosscheck": cross.to_dict("records"),
        "density_range_kg_m3": analysis.density_summary(runs),
        "hysteresis": {"runs": len(runs), "events_with": n_with, "events_without": n_without},
        "fusion_simulation": fusion_simulation(fx),
        "headline": {
            "max_util_primary": float(p["max_util"].max()),
            "max_util_all": float(summ["max_util"].max()),
            "days_ge_70_all": int(summ["days_ge_70"].sum()),
            "runs": int(len(summ)),
        },
    }


def _md_table(rows: list[dict], cols: list[str]) -> str:
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    return head + "\n".join("| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows)


def to_markdown(res: dict) -> str:
    sm = res["summary"]
    cols = ["station", "winter", "altitude_m", "design_kn_m2", "max_hs_cm", "max_load_kn_m2",
            "max_util", "peak_day", "days_ge_50", "days_ge_70", "days_ge_90", "alert_events"]
    out = ["# Results (generated by `python -m roofsnow demo`)", "",
           "Default density model: layered. Z = 0, flat roof, normal exposure.", "",
           "## Utilisation per station and winter", "", _md_table(sm, cols), "",
           "## Conservative bound (Sturm regression)", "",
           _md_table(res["summary_conservative_sturm"], ["station", "winter", "max_load_kn_m2", "max_util",
                                                          "days_ge_70", "days_ge_90"]), "",
           f"## Density-model sensitivity, winter {res['primary_winter']}", "",
           _md_table(res["sensitivity_primary"], ["station", "model", "max_swe_mm", "max_load_kn_m2",
                                                  "max_util", "days_ge_70", "mean_rho_kg_m3"]), "",
           "## Cross-check: layered vs mass-balance SWE (model vs model, not measured SWE)", "",
           _md_table(res["crosscheck"], ["station", "winter", "days", "bias_pct", "rmse_mm", "corr"]), "",
           f"Hysteresis over all {res['hysteresis']['runs']} station-winters: "
           f"{res['hysteresis']['events_with']} level changes with 5-point hysteresis, "
           f"{res['hysteresis']['events_without']} without.", "",
           "## Sensor fusion (SIMULATED sensor)", "", "```json",
           json.dumps(res["fusion_simulation"], indent=1), "```", ""]
    return "\n".join(out)


def write(res: dict, out_dir: str | Path) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.json").write_text(json.dumps(res, indent=1, default=str), encoding="utf-8")
    (out / "results.md").write_text(to_markdown(res), encoding="utf-8")
